"""Generate the Apple localization artifacts from shared/strings.json.

The JSON stays the single source of truth: the Rust core compiles it for the Windows, GTK and
Android shells, and this script only derives what Xcode and Bundle.main expect.

It writes two things, both generated and never edited by hand:

  shared/apple/Localizable.xcstrings           the String Catalog Xcode builds and translators open
  shared/apple/<language>.lproj/Localizable.strings   the same table, for a bundle assembled by hand

With --check it writes nothing and fails when either file is out of date, so CI catches a table
change that was not regenerated.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "shared/strings.json"
OUTPUT = ROOT / "shared/apple"
CATALOG = OUTPUT / "Localizable.xcstrings"
# Xcode compiles a catalog that sits inside a target's source folder; each target needs its own copy.
TARGETS = [
    ROOT / "app-macos/Sources/DrawKit/Localizable.xcstrings",
    ROOT / "app-ios/Sources/DrawKit/Localizable.xcstrings",
]


def source_language(data):
    return data.get("fallback", "en")


def catalog_rows(data):
    """English text -> per-language text. The older camelCase keys share the same catalog space,
    so a row with the same English text is folded in; a different translation for the same English
    text is a hard error instead of a silent coin toss."""
    rows = {}
    origin = {}
    fallback = source_language(data)
    for key, row in data["strings"].items():
        english = row.get(fallback) or key
        if english in rows:
            for language, value in row.items():
                if rows[english].get(language) not in (None, value):
                    print(f"conflict: {english!r} has two translations in {language} "
                          f"({origin[english]} and {key})", file=sys.stderr)
                    raise SystemExit(1)
                rows[english][language] = value
        else:
            rows[english] = dict(row)
            origin[english] = key
    return rows


def write_catalog(rows, language):
    strings = {}
    for english in sorted(rows):
        localizations = {}
        for code, value in sorted(rows[english].items()):
            if not value:
                continue
            localizations[code] = {
                "stringUnit": {"state": "translated", "value": value},
            }
        strings[english] = {
            "extractionState": "manual",
            "localizations": localizations,
        }
    document = {
        "sourceLanguage": language,
        "strings": strings,
        "version": "1.0",
    }
    return json.dumps(document, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def quote(value):
    return (value.replace("\\", "\\\\").replace('"', '\\"')
            .replace("\n", "\\n").replace("\t", "\\t"))


def write_strings(rows, language):
    lines = [
        "/* Generated by scripts/gen-apple-strings.py from shared/strings.json. */",
        "",
    ]
    for english in sorted(rows):
        value = rows[english].get(language) or rows[english].get("en") or english
        lines.append(f"\"{quote(english)}\" = \"{quote(value)}\";")
    return "\n".join(lines) + "\n"


def plans(data):
    rows = catalog_rows(data)
    language = source_language(data)
    catalog = write_catalog(rows, language)
    files = {path: catalog for path in [CATALOG, *TARGETS]}
    for code in data["languages"]:
        files[OUTPUT / f"{code}.lproj" / "Localizable.strings"] = write_strings(rows, code)
    return files


def main():
    check = "--check" in sys.argv
    data = json.loads(SOURCE.read_text())
    files = plans(data)
    stale = []
    for path, content in files.items():
        if path.exists() and path.read_text() == content:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if check and stale:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        raise SystemExit(1)
    print(f"{len(files)} files, {len(stale)} written"
          + ("" if not check else " (check only))".replace("))", ")")))


if __name__ == "__main__":
    main()
